def main() -> int:
    random.seed(42)
    attacks_path = HERE / "attacks_heldout.jsonl"
    benign_path = HERE / "benign_heldout.jsonl"
    with attacks_path.open("w", encoding="utf-8") as fh:
        for item in attacks():
            fh.write(json.dumps(item, ensure_ascii=False) + "\n")
    with benign_path.open("w", encoding="utf-8") as fh:
        for text in benign():
            fh.write(json.dumps({"text": text}, ensure_ascii=False) + "\n")
    print("wrote %s (%d) and %s (%d)" % (
        attacks_path, sum(1 for _ in attacks_path.open(encoding="utf-8")),
        benign_path, sum(1 for _ in benign_path.open(encoding="utf-8"))))
    return 0


